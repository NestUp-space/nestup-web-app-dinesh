/**
 * Port of updateBoxPosition — updates all planks in a box.
 */
export function updateBoxPositionInData(
  rawValues: unknown[][],
  plankUpdates: { rowIndex: number; newX: number; newY: number; newZ: number }[]
): { success: boolean; updatedCount?: number; error?: string } {
  if (!rawValues || rawValues.length === 0) {
    return { success: false, error: 'Data is empty' };
  }

  const headers = rawValues[0];
  const lowerHeaders = (headers as unknown[]).map((h) =>
    (h || '').toString().trim().toLowerCase()
  );

  const xCol = lowerHeaders.indexOf('x');
  const yCol = lowerHeaders.indexOf('y');
  const zCol = lowerHeaders.indexOf('z');

  if (xCol < 0 || yCol < 0 || zCol < 0) {
    return { success: false, error: 'X, Y, or Z columns not found' };
  }

  let updatedCount = 0;
  for (const update of plankUpdates) {
    const { rowIndex, newX, newY, newZ } = update;
    if (rowIndex && rowIndex > 0 && rowIndex < rawValues.length) {
      (rawValues[rowIndex] as unknown[])[xCol] = Math.round(newX) + ' mm';
      (rawValues[rowIndex] as unknown[])[yCol] = Math.round(newY) + ' mm';
      (rawValues[rowIndex] as unknown[])[zCol] = Math.round(newZ) + ' mm';
      updatedCount++;
    }
  }

  return { success: true, updatedCount };
}
