export interface Position {
  x: number;
  y: number;
  z: number;
}

export interface Dimensions {
  lenX: number;
  lenY: number;
  lenZ: number;
}

export interface PlankData {
  id: string;
  entityName: string;
  material: string;
  materialColor: string;
  position: Position;
  dimensions: Dimensions;
  role: string;
  explodeDirection: Position;
  assemblyDirection: { arrow: string; text: string };
  isDoor: boolean;
  hingeSide: string;
  assemblyOrder: number;
  autoGenerated: boolean;
  rowIndex: number;
  stepNumber?: number;
}

export interface ChecklistItem {
  id: string;
  name: string;
  material: string;
  dimensions: string;
  checked: boolean;
}

export interface BoxData {
  id: string;
  entityName: string;
  roomName: string;
  unitLocation: string;
  boxModel: string;
  boxType: string;
  position: Position;
  dimensions: Dimensions;
  planks: PlankData[];
  checklist: ChecklistItem[];
  rowIndex: number;
  totalSteps?: number;
}

export interface WallData {
  id: string;
  entityName: string;
  roomName: string;
  unitLocation: string;
  material: string;
  position: Position;
  dimensions: Dimensions;
  boxes: BoxData[];
  rowIndex: number;
}

export interface MaterialLegendItem {
  name: string;
  color: string;
}

export interface VisualizationData {
  walls: WallData[];
  materialLegend: MaterialLegendItem[];
  summary: {
    totalWalls: number;
    totalBoxes: number;
    totalPlanks: number;
    timestamp: string;
    autoGeneratedIds: number;
  };
}

// =================================================================
// =================== HEADER PARSING ===================
// =================================================================

function parseHeaders(headerRow: unknown[]): Record<string, number> | null {
  const rawHeaders = headerRow.map((h) => (h || '').toString().trim());
  const lowerHeaders = rawHeaders.map((h) => h.toLowerCase().replace(/\s+/g, ' '));
  const headerIndex: Record<string, number> = {};

  lowerHeaders.forEach((h, i) => {
    const normalized = h.replace(/[\s_]/g, '');

    if (normalized === 'entityname' || h === 'entity name' || h === 'entity_name')
      headerIndex['entity name'] = i;
    if (normalized === 'level' || h === 'level') headerIndex['level'] = i;
    if (normalized === 'material' || h === 'material') headerIndex['material'] = i;
    if (normalized === 'roomname' || h === 'room_name' || h === 'room name')
      headerIndex['room_name'] = i;
    if (normalized === 'unitlocation' || h === 'unit_location' || h === 'unit location')
      headerIndex['unit_location'] = i;
    if (normalized === 'boxmodel' || h === 'box_model' || h === 'box model')
      headerIndex['box_model'] = i;
    if (normalized === 'boxtype' || h === 'box_type' || h === 'box type')
      headerIndex['box_type'] = i;
    if (h === 'x') headerIndex['x'] = i;
    if (h === 'y') headerIndex['y'] = i;
    if (h === 'z') headerIndex['z'] = i;
    if (normalized === 'lenx' || h === 'len_x' || h === 'len x') headerIndex['lenx'] = i;
    if (normalized === 'leny' || h === 'len_y' || h === 'len y') headerIndex['leny'] = i;
    if (normalized === 'lenz' || h === 'len_z' || h === 'len z') headerIndex['lenz'] = i;
    if (normalized === 'plankid' || h === 'plank_id' || h === 'plank id')
      headerIndex['plank_id'] = i;
  });

  const requiredHeaders = [
    'level', 'entity name', 'material', 'room_name', 'unit_location',
    'box_model', 'box_type', 'x', 'y', 'z', 'lenx', 'leny', 'lenz',
    'plank_id',
  ];

  const missing = requiredHeaders.filter((req) => headerIndex[req] === undefined);
  if (missing.length > 0) {
    console.warn('Missing headers:', missing.join(', '));
    return null;
  }

  return headerIndex;
}

function parseNumber(value: unknown): number {
  const cleaned = String(value).replace(/[^0-9.\-]/g, '');
  const n = parseFloat(cleaned);
  return isNaN(n) ? 0 : n;
}

// =================================================================
// =================== HIERARCHY BUILDER ===================
// =================================================================

function buildHierarchy(
  values: unknown[][],
  headerIndex: Record<string, number>
): VisualizationData {
  const walls: WallData[] = [];
  let currentWall: WallData | null = null;
  let currentBox: BoxData | null = null;
  let globalBoxId = 1;
  let wallId = 1;

  for (let r = 1; r < values.length; r++) {
    const row = values[r];
    if ((row as unknown[]).every((cell) => String(cell).trim() === '')) continue;

    const level = String(row[headerIndex['level']]).trim().toLowerCase();
    const entityName = String(row[headerIndex['entity name']] || '').trim();
    const material = String(row[headerIndex['material']] || '').trim();
    const roomName = String(row[headerIndex['room_name']] || '').trim();
    const unitLocation = String(row[headerIndex['unit_location']] || '').trim();
    const boxModel = String(row[headerIndex['box_model']] || '').trim();
    const boxType = String(row[headerIndex['box_type']] || '').trim();

    const X = parseNumber(row[headerIndex['x']]);
    const Y = parseNumber(row[headerIndex['y']]);
    const Z = parseNumber(row[headerIndex['z']]);
    const lenX = parseNumber(row[headerIndex['lenx']]);
    const lenY = parseNumber(row[headerIndex['leny']]);
    const lenZ = parseNumber(row[headerIndex['lenz']]);

    const rawPlankId = row[headerIndex['plank_id']];
    const plankId =
      rawPlankId !== undefined && rawPlankId !== null && String(rawPlankId).trim() !== ''
        ? String(rawPlankId).trim()
        : null;

    if (level === '0' || level === 'wall') {
      if (currentWall) walls.push(currentWall);
      currentWall = {
        id: `wall_${wallId++}`,
        entityName,
        roomName,
        unitLocation,
        material,
        position: { x: X, y: Y, z: Z },
        dimensions: { lenX: lenX || 5000, lenY: lenY || 200, lenZ: lenZ || 3000 },
        boxes: [],
        rowIndex: r + 1,
      };
      currentBox = null;
    } else if ((level === '1' || level.startsWith('box')) && currentWall) {
      currentBox = {
        id: `box_${globalBoxId++}`,
        entityName,
        roomName,
        unitLocation,
        boxModel,
        boxType,
        position: { x: X, y: Y, z: Z },
        dimensions: { lenX, lenY, lenZ },
        planks: [],
        checklist: [],
        rowIndex: r + 1,
      };
      currentWall.boxes.push(currentBox);
    } else if ((level === '2' || level.startsWith('plank')) && currentBox) {
      if (lenX <= 0 || lenY <= 0 || lenZ <= 0) continue;

      const plankRole = determinePlankRole(entityName);
      const materialColor = getMaterialColor(material);

      const plank: PlankData = {
        id: plankId || 'NO ID',
        entityName,
        material,
        materialColor,
        position: { x: X, y: Y, z: Z },
        dimensions: { lenX, lenY, lenZ },
        role: plankRole,
        explodeDirection: getExplodeDirection(plankRole),
        assemblyDirection: getAssemblyDirection(plankRole),
        isDoor: plankRole === 'door',
        hingeSide: determineHingeSide(entityName),
        assemblyOrder: getAssemblyOrder(plankRole),
        autoGenerated: false,
        rowIndex: r + 1,
      };

      currentBox.planks.push(plank);
      currentBox.checklist.push({
        id: plank.id,
        name: entityName,
        material,
        dimensions: `${lenX} × ${lenY} × ${lenZ}`,
        checked: false,
      });
    }
    // Level 3 (holes/operations) — ignored for installation guide
  }

  if (currentWall) walls.push(currentWall);

  walls.forEach((wall) => {
    wall.boxes.forEach((box) => {
      box.planks.sort((a, b) => a.assemblyOrder - b.assemblyOrder);
      box.planks.forEach((plank, index) => {
        plank.stepNumber = index + 1;
      });
      box.totalSteps = box.planks.length;
    });
  });

  const totalBoxes = walls.reduce((sum, w) => sum + w.boxes.length, 0);
  const totalPlanks = walls.reduce(
    (sum, w) => sum + w.boxes.reduce((s, b) => s + b.planks.length, 0),
    0
  );

  const materialsSet = new Set<string>();
  walls.forEach((wall) => {
    wall.boxes.forEach((box) => {
      box.planks.forEach((plank) => {
        if (plank.material) materialsSet.add(plank.material);
      });
    });
  });

  const materialLegend: MaterialLegendItem[] = Array.from(materialsSet).map((mat) => ({
    name: mat,
    color: getMaterialColor(mat),
  }));

  return {
    walls,
    materialLegend,
    summary: {
      totalWalls: walls.length,
      totalBoxes,
      totalPlanks,
      timestamp: new Date().toISOString(),
      autoGeneratedIds: 0,
    },
  };
}

