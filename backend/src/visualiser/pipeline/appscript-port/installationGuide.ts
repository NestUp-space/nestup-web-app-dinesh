  if (lenXCol >= 0) (rawValues[rowIndex] as unknown[])[lenXCol] = newLenX + ' mm';
  if (lenYCol >= 0) (rawValues[rowIndex] as unknown[])[lenYCol] = newLenY + ' mm';
  if (lenZCol >= 0) (rawValues[rowIndex] as unknown[])[lenZCol] = newLenZ + ' mm';

  return { success: true };
