// ============================================
// CATALOG
// ============================================

export interface CatalogModel {
  id: string;
  entityName: string;
  level: number;
  material?: string;
  roomName?: string;
  unitLocation?: string;
  boxModel: string;
  boxType: string;
  lenX: number;
  lenY: number;
  lenZ: number;
  boxWidth: number;
  boxDepth: number;
  boxHeight: number;
  skirting: number;
  skirtingWidth: number;
  carcusThickness: number;
  doorThickness: number;
  backplankThickness: number;
  plankTemplates?: PlankTemplate[];
}

export interface PlankTemplate {
  entityName: string;
  material: string;
  level: number;
  rowIndex: number;
  lenX: number;
  lenY: number;
  lenZ: number;
  x: number;
  y: number;
  z: number;
  /** Level-3 features attached while parsing Google Sheets */
  subComponents?: unknown[];
}

/** Parsed catalog box with child planks (designer palette) */
export interface CatalogBoxWithPlanks extends CatalogModel {
  planks: PlankTemplate[];
}

export interface PlywoodOption {
  id: string;
  sno: string;
  brand: string;
  gradeType: string;
  material: string;
  thickness: number;
  price: number;
  remarks?: string;
  displayName: string;
}

export interface LaminateOption {
  id: string;
  sno: string;
  brand: string;
  code: string;
  colour: string;
  thickness: number;
  price: number;
  photoUrl?: string;
  comments?: string;
  displayName: string;
}

export interface CatalogData {
  models: CatalogModel[];
  plywoodOptions: PlywoodOption[];
  laminateOptions: LaminateOption[];
  /** Optional; required for 3D designer “add from catalog” */
  catalogBoxesWithPlanks?: CatalogBoxWithPlanks[];
  source: 'google-sheets' | 'csv';
}

